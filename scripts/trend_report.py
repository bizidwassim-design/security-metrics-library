#!/usr/bin/env python3
"""
Render a Markdown trend report with Unicode sparklines from a CSV of monthly metric values.

Input CSV columns: metric_id, month (YYYY-MM), value
Metric metadata (name, unit, direction, target) comes from data/metrics.yaml.

Usage:
    pip install pyyaml
    python scripts/trend_report.py                                   # examples/sample-values.csv -> examples/trend-report.md
    python scripts/trend_report.py --values my-values.csv --out report.md

Status rules
    On target     latest value meets the target in the metric's direction
    Near target   within 10 % of the target (relative), not yet met
    Off target    everything else
Trend rules (last 3 months vs previous 3 months, in the metric's direction)
    Improving / Worsening when the change is larger than 2 % of the earlier average, otherwise Flat
"""
from __future__ import annotations

import argparse
import csv
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_VALUES = ROOT / "examples" / "sample-values.csv"
DEFAULT_OUT = ROOT / "examples" / "trend-report.md"
DEFAULT_YAML = ROOT / "data" / "metrics.yaml"

BARS = "▁▂▃▄▅▆▇█"   # ▁▂▃▄▅▆▇█
NEAR_TOLERANCE = 0.10
FLAT_TOLERANCE = 0.02


def sparkline(values: list[float]) -> str:
    """Map a series to eight-level block characters. A flat series renders mid-height."""
    if not values:
        return ""
    lo, hi = min(values), max(values)
    if hi == lo:
        return BARS[3] * len(values)
    span = hi - lo
    return "".join(BARS[min(7, int((v - lo) / span * 7.999))] for v in values)


def meets(value: float, target: float, direction: str) -> bool:
    return value >= target if direction == "higher" else value <= target


def status(latest: float, target: float, direction: str) -> str:
    if meets(latest, target, direction):
        return "On target"
    tolerance = abs(target) * NEAR_TOLERANCE if target else NEAR_TOLERANCE
    if abs(latest - target) <= tolerance:
        return "Near target"
    return "Off target"


def trend(values: list[float], direction: str) -> str:
    if len(values) < 4:
        return "n/a"
    k = min(3, len(values) // 2)
    recent = sum(values[-k:]) / k
    earlier = sum(values[-2 * k:-k]) / k
    base = abs(earlier) if earlier else 1.0
    delta = (recent - earlier) / base
    if abs(delta) <= FLAT_TOLERANCE:
        return "Flat"
    better = delta > 0 if direction == "higher" else delta < 0
    return "Improving" if better else "Worsening"


def fmt(value: float, unit: str) -> str:
    text = f"{value:.1f}".rstrip("0").rstrip(".")
    return f"{text} %" if unit == "%" else f"{text} {unit}" if unit in {"days", "hours"} else text


def load_metadata(path: Path) -> dict[str, dict[str, Any]]:
    with path.open(encoding="utf-8") as fh:
        data = yaml.safe_load(fh)
    return {m["id"]: m for m in data["metrics"]}


def load_values(path: Path) -> dict[str, list[tuple[str, float]]]:
    series: dict[str, list[tuple[str, float]]] = defaultdict(list)
    with path.open(encoding="utf-8", newline="") as fh:
        reader = csv.DictReader(fh)
        expected = {"metric_id", "month", "value"}
        if not reader.fieldnames or not expected.issubset(reader.fieldnames):
            raise ValueError(f"{path}: columns must include {sorted(expected)}")
        for row in reader:
            series[row["metric_id"].strip()].append((row["month"].strip(), float(row["value"])))
    for key in series:
        series[key].sort(key=lambda t: t[0])
    return series


def render(series: dict[str, list[tuple[str, float]]], meta: dict[str, dict[str, Any]], source_name: str) -> list[str]:
    months = sorted({m for s in series.values() for m, _ in s})
    lines = [
        "# Security metrics trend report",
        "",
        f"<!-- Generated by scripts/trend_report.py from {source_name}. Do not edit by hand. -->",
        "",
        f"Period: {months[0]} to {months[-1]} ({len(months)} months). Values are fictional sample data. "
        "Sparklines scale each metric to its own minimum and maximum, so they show shape, not magnitude.",
        "",
        "| ID | Metric | Trend (oldest → latest) | First | Latest | Change | Target | Status | Direction |",
        "|----|--------|-------------------------|------:|-------:|-------:|-------:|--------|-----------|",
    ]
    counts = {"On target": 0, "Near target": 0, "Off target": 0}
    detail: list[str] = []
    for mid in sorted(series):
        if mid not in meta:
            raise KeyError(f"{mid} is not defined in metrics.yaml")
        m = meta[mid]
        vals = [v for _, v in series[mid]]
        first, latest = vals[0], vals[-1]
        st = status(latest, float(m["target_value"]), m["direction"])
        tr = trend(vals, m["direction"])
        counts[st] += 1
        change = latest - first
        sign = "+" if change > 0 else ""
        lines.append(
            f"| {mid} | {m['name']} | `{sparkline(vals)}` | {fmt(first, m['unit'])} | **{fmt(latest, m['unit'])}** | "
            f"{sign}{fmt(change, m['unit'])} | {fmt(float(m['target_value']), m['unit'])} | {st} | {tr} |"
        )
        best = max(vals) if m["direction"] == "higher" else min(vals)
        worst = min(vals) if m["direction"] == "higher" else max(vals)
        detail += [
            f"### {mid} — {m['name']}", "",
            f"`{sparkline(vals)}`  {m['direction']} is better · target {m['target_example']} · {st}, {tr.lower()}", "",
            "| Month | " + " | ".join(mo for mo, _ in series[mid]) + " |",
            "|-------|" + "|".join("-----:" for _ in series[mid]) + "|",
            "| Value | " + " | ".join(fmt(v, m['unit']) for _, v in series[mid]) + " |",
            "",
            f"Best {fmt(best, m['unit'])}, worst {fmt(worst, m['unit'])}, average {fmt(sum(vals) / len(vals), m['unit'])}. "
            f"Watch for: {m['pitfalls'][0]}",
            "",
        ]
    lines += ["", f"**Summary:** {counts['On target']} on target, {counts['Near target']} near target, "
              f"{counts['Off target']} off target, out of {len(series)} metrics.", "", "## Detail", ""]
    lines += detail
    return lines


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--values", type=Path, default=DEFAULT_VALUES, help="CSV with metric_id, month, value")
    parser.add_argument("--metrics", type=Path, default=DEFAULT_YAML, help="metrics.yaml with metadata")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="Markdown file to write")
    args = parser.parse_args(argv)

    meta = load_metadata(args.metrics)
    series = load_values(args.values)
    if not series:
        print("no values found", file=sys.stderr)
        return 1
    lines = render(series, meta, args.values.name)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {args.out} ({len(series)} metrics, {len(lines)} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
